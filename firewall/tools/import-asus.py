#!/usr/bin/env python3
"""Turn an ASUS migration dump into dnsmasq files. The dump script is not part of this repository.

Writes:
  profiles/prod/etc/dnsmasq.d/20-reservations.conf   dhcp-host lines from dhcp_staticlist
  out/dnsmasq.leases.seed                             (--leases) current leases as dnsmasq lease lines, for cutover

Usage:  python tools/import-asus.py ..\\reports\\asus-migration-dump-<stamp>.txt [--leases]
The dump is already redacted; this reads only dhcp_staticlist, the lease section and the dump time.
"""
from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "profiles" / "prod" / "etc" / "dnsmasq.d" / "20-reservations.conf"
SEED = ROOT / "out" / "dnsmasq.leases.seed"
MAC = re.compile(r"^[0-9a-f]{2}(:[0-9a-f]{2}){5}$")


def hostname(name: str) -> str:
    h = re.sub(r"[^a-z0-9-]", "-", name.lower()).strip("-")
    return h[:63] or "host"


def reservations(text: str) -> list[tuple[str, str, str]]:
    m = re.search(r"^dhcp_staticlist=(.*)$", text, re.M)
    if not m:
        sys.exit("dhcp_staticlist not found in the dump")
    out = []
    for item in m.group(1).split("<"):
        if not item:
            continue
        parts = item.split(">")
        mac, ip = parts[0].lower(), parts[1]
        name = parts[2] if len(parts) > 2 and parts[2] else ip.replace(".", "-")
        if not MAC.match(mac):
            sys.exit(f"bad MAC in dhcp_staticlist: {mac}")
        out.append((mac, ip, hostname(name)))
    return out


def dump_time(path: Path) -> dt.datetime:
    m = re.search(r"(\d{8}-\d{6})", path.name)
    if not m:
        sys.exit("cannot read the dump time from the file name (asus-migration-dump-YYYYmmdd-HHMMSS.txt)")
    return dt.datetime.strptime(m.group(1), "%Y%m%d-%H%M%S")


def leases(text: str, taken: dt.datetime) -> list[str]:
    m = re.search(r"^--- leases \(\d+\) ---\n(.*?)(?=^=====)", text, re.M | re.S)
    if not m:
        sys.exit("lease section not found in the dump")
    base = int(taken.timestamp())
    out = []
    for line in m.group(1).splitlines():
        f = line.split()
        if len(f) < 5 or not f[0].isdigit() or not MAC.match(f[1].lower()):
            continue
        remaining, mac, ip, host, cid = f[:5]
        if not ip.startswith("192.168.50."):
            continue  # the guest network had no clients; the firewall's own bench lease is not carried over
        if mac.lower() == "00:00:5e:00:53:10":
            continue
        if not re.fullmatch(r"[A-Za-z0-9-]{1,63}", host):
            host = "*"  # dnsmasq would reject names with an underscore; the client sends its name again on renew
        out.append(f"{base + int(remaining)} {mac.lower()} {ip} {host} {cid}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dump", type=Path)
    ap.add_argument("--leases", action="store_true", help="also write out/dnsmasq.leases.seed")
    a = ap.parse_args()
    text = a.dump.read_text(encoding="utf-8")

    rows = reservations(text)
    lines = [
        f"# DHCP reservations from the ASUS (dhcp_staticlist), dump {a.dump.name}.",
        "# Generated by tools/import-asus.py. Edit here or regenerate; dnsmasq also serves these names in DNS.",
    ]
    lines += [f"dhcp-host={mac},{ip},{name}" for mac, ip, name in rows]
    RES.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{RES} ({len(rows)} reservations)")

    if a.leases:
        seed = leases(text, dump_time(a.dump))
        SEED.parent.mkdir(exist_ok=True)
        SEED.write_text("\n".join(seed) + "\n", encoding="utf-8", newline="\n")
        print(f"{SEED} ({len(seed)} leases; local times assume the dump was taken on this PC's clock)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
